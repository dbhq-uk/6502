    /// <summary>The code in the SAA5050 English set that shows <paramref name="glyph"/> (s4.4).</summary>
    public static int Code(char glyph) => glyph switch
    {
        '£' => 0x23,
        '←' => 0x5B,
        '½' => 0x5C,
        '→' => 0x5D,
        '↑' => 0x5E,
        '#' => 0x5F,
        '_' => 0x60,
        '¼' => 0x7B,
        '‖' => 0x7C,
        '¾' => 0x7D,
        '÷' => 0x7E,
        '■' => 0x7F,
        _ => glyph,
    };

    /// <summary>A grid's row as five bits, the leftmost dot in bit 4.</summary>
    public static int Bits(string row)
    {
        int bits = 0;
        foreach (char dot in row)
        {
            bits = (bits << 1) | (dot == '#' ? 1 : 0);
        }
        return bits;
    }
